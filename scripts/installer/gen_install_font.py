#!/usr/bin/env python3
"""Generates the installer's glyph table and string table for the kernel.

Only codepoints used by strings.py are rendered (keeps the kernel image small).
  Latin / Latin-1 / Cyrillic : LiberationSans-Regular.ttf
  Hangul                     : NotoSansCJK KR
  Hanzi, CJK punctuation     : NotoSansCJK SC
Outputs (into userspace/installer/):
  installer_glyphs.h   8-bit alpha bitmaps, 24 px line height, per-glyph advance width
  installer_strings.h  language table (UTF-8)

Usage: python3 gen_install_font.py --latin LiberationSans-Regular.ttf \
          --cjk NotoSansCJK-Regular.ttc --out kernel/
"""
import argparse, json, os, sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTCollection, TTFont
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from strings import LANGS, MSG_KEYS, MSGS

ap = argparse.ArgumentParser()
ap.add_argument("--latin", required=True)
ap.add_argument("--cjk", required=True)
ap.add_argument("--out", required=True)
args = ap.parse_args()
PX = 28

def is_hangul(c): return 0xAC00 <= c <= 0xD7A3 or 0x1100 <= c <= 0x11FF or 0x3130 <= c <= 0x318F
def is_han(c): return 0x4E00 <= c <= 0x9FFF or 0x3000 <= c <= 0x303F or 0xFF00 <= c <= 0xFFEF

codes = sorted({ord(ch) for row in LANGS for s in row[1:] for ch in s if not ch.isspace()}
               | {ord(ch) for lst in MSGS.values() for s in lst for ch in s if not ch.isspace()}
               | set(range(0x21, 0x7F)))  # + printable ASCII for the log lines
assert all(len(MSGS[row[0]]) == len(MSG_KEYS) for row in LANGS), "every language needs all MSG_KEYS"
lat_cmap = TTFont(args.latin).getBestCmap()
names = [str(f["name"].getDebugName(4)) for f in TTCollection(args.cjk).fonts]
kr_idx = names.index("Noto Sans CJK KR")   # exact names: not "Noto Sans Mono CJK KR"
sc_idx = names.index("Noto Sans CJK SC")

cache = {}
def font_for(c):
    if c in lat_cmap:
        key = "lat"
        if key not in cache: cache[key] = ImageFont.truetype(args.latin, PX)
    elif is_hangul(c) or is_han(c):
        key = ("cjk", kr_idx if is_hangul(c) else sc_idx)
        if key not in cache: cache[key] = ImageFont.truetype(args.cjk, PX, index=key[1])
    else:
        raise SystemExit("no font covers U+%04X (%r)" % (c, chr(c)))
    return ("cjk" if key != "lat" else "lat"), cache[key]

entries, data = [], bytearray()
for c in codes:
    kind, f = font_for(c)
    ch = chr(c)
    w = PX if kind == "cjk" else max(int(round(f.getlength(ch))), 1)
    img = Image.new("L", (w, PX), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=f, fill=255)
    entries.append((c, w, len(data)))
    data += img.tobytes()

os.makedirs(args.out, exist_ok=True)
gp = os.path.join(args.out, "installer_glyphs.h")
with open(gp, "w", encoding="utf-8") as h:
    h.write("/* Generated by scripts/installer/gen_install_font.py: %d glyphs, %d bytes. Do not edit. */\n" % (len(entries), len(data)))
    h.write("#pragma once\n#include <stdint.h>\n\n#define INSTALLER_GLYPH_HEIGHT %d\n" % PX)
    h.write("struct InstallerGlyph { uint32_t cp; uint8_t width; uint32_t offset; };\n")
    h.write("/* sorted by cp: binary search */\n")
    h.write("static const struct InstallerGlyph installer_glyph_table[] = {\n")
    for c, w, off in entries:
        h.write("    {0x%04X, %d, %d},\n" % (c, w, off))
    h.write("};\nstatic const uint32_t installer_glyph_count = %d;\n" % len(entries))
    h.write("static const uint8_t installer_glyph_alpha[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        h.write("    " + ",".join("%d" % b for b in data[i:i+16]) + ",\n")
    h.write("};\n")

sp = os.path.join(args.out, "installer_strings.h")
with open(sp, "w", encoding="utf-8") as h:
    h.write("/* Generated by scripts/installer/gen_install_font.py from strings.py. Do not edit. */\n#pragma once\n\n")
    h.write("struct InstallerLang { const char* code; const char* native; const char* title; const char* pick; const char* hint; const char* welcome; };\n")
    h.write("static const struct InstallerLang installer_langs[] = {\n")
    for row in LANGS:
        h.write("    {" + ", ".join(json.dumps(x, ensure_ascii=False) for x in row) + "},\n")
    h.write("};\nstatic const uint32_t installer_lang_count = %d;\n" % len(LANGS))
    h.write("\n/* Disk-stage messages: installer_msgs[language index][MSG_*]. Same language order as installer_langs. */\n")
    h.write("enum InstallerMsg {\n")
    for k in MSG_KEYS:
        h.write("    MSG_%s,\n" % k)
    h.write("    MSG_COUNT\n};\n")
    h.write("static const char *const installer_msgs[][MSG_COUNT] = {\n")
    for row in LANGS:
        h.write("    {" + ", ".join(json.dumps(x, ensure_ascii=False) for x in MSGS[row[0]]) + "},\n")
    h.write("};\n")
print("glyphs=%d bytes=%d langs=%d -> %s" % (len(entries), len(data), len(LANGS), args.out))
