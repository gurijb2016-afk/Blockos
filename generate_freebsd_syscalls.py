#!/usr/bin/env python3
"""Generate a metadata-only index from FreeBSD syscalls.master.

This does NOT generate syscall implementations or replace BlockOS's native ABI.
It intentionally preserves FreeBSD syscall numbers in a separate namespace.
"""
from __future__ import annotations
import argparse, csv, pathlib, re, sys

ROW = re.compile(r'^\s*(\d+)\s+(\S+)\s+(\S+)\s+(.*)$')
FUNC = re.compile(r'\b([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*(?:\n|.)*?\)', re.S)


def parse(path: pathlib.Path):
    lines = path.read_text(encoding='utf-8', errors='replace').splitlines()
    entries = []
    i = 0
    while i < len(lines):
        m = ROW.match(lines[i])
        if not m:
            i += 1; continue
        nr, audit, kind, rest = m.groups()
        start = i
        i += 1
        # A prototype body continues until the next numbered row. Keep the original
        # prototype text for review; do not infer that it is implemented in BlockOS.
        body = [rest]
        while i < len(lines) and not ROW.match(lines[i]):
            body.append(lines[i]); i += 1
        raw = '\n'.join(body).strip()
        if kind == 'SYSMUX':
            name = rest.split('{', 1)[0].strip() or 'syscall'
            status = 'multiplexer'
        elif kind == 'OBSOL':
            name = rest.split()[0] if rest.split() else 'unknown'
            status = 'obsolete'
        elif kind == 'RESERVED':
            name = rest.split()[0] if rest.split() else 'reserved'
            status = 'reserved'
        elif kind == 'UNIMPL':
            name = rest.split()[0] if rest.split() else 'unimplemented-placeholder'
            status = 'unimplemented-placeholder'
        else:
            # FreeBSD master rows usually have a { ... } prototype. Extract the
            # function identifier immediately before its opening parenthesis.
            head = raw.split('{', 1)[-1]
            names = re.findall(r'\b([A-Za-z_][A-Za-z0-9_]*)\s*\(', head)
            name = names[0] if names else (rest.split()[0] if rest.split() else 'unknown')
            status = 'defined-in-master'
        entries.append({
            'number': int(nr), 'audit': audit, 'type': kind,
            'name': name, 'status': status,
            'prototype': re.sub(r'\s+', ' ', raw).strip(),
            'source_line': start + 1,
        })
    if not entries:
        raise ValueError(f'No syscall rows parsed from {path}')
    nums = [e['number'] for e in entries]
    if len(nums) != len(set(nums)):
        raise ValueError('Duplicate syscall numbers found')
    if nums != sorted(nums):
        raise ValueError('Syscall numbers are not in ascending order')
    return entries


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('master', type=pathlib.Path)
    ap.add_argument('--out', type=pathlib.Path, required=True)
    args = ap.parse_args()
    entries = parse(args.master)
    args.out.mkdir(parents=True, exist_ok=True)
    with (args.out / 'freebsd_syscalls.csv').open('w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=['number','audit','type','name','status','prototype','source_line'])
        w.writeheader(); w.writerows(entries)
    h = args.out / 'freebsd_syscall_metadata.hpp'
    c = args.out / 'freebsd_syscall_metadata.cpp'
    h.write_text('''// Generated by cpy/tools/generate_freebsd_syscalls.py. DO NOT EDIT.\n#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace blockos::freebsd_abi {\nstruct SyscallMetadata { std::uint16_t number; const char* name; const char* type; const char* audit; const char* status; };\nconst SyscallMetadata* lookup(std::uint16_t number) noexcept;\nstd::size_t count() noexcept;\n}\n''', encoding='utf-8')
    def q(s):
        return '"' + s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n') + '"'
    rows = ',\n'.join('    {%d, %s, %s, %s, %s}' % (e['number'], q(e['name']), q(e['type']), q(e['audit']), q(e['status'])) for e in entries)
    c.write_text('''// Generated by cpy/tools/generate_freebsd_syscalls.py. DO NOT EDIT.\n#include "freebsd_syscall_metadata.hpp"\nnamespace blockos::freebsd_abi {\nnamespace { constexpr SyscallMetadata table[] = {\n'''+rows+'''\n}; }\nconst SyscallMetadata* lookup(std::uint16_t number) noexcept {\n    // Entries are sorted; binary search keeps lookup bounded.\n    std::size_t lo = 0, hi = sizeof(table) / sizeof(table[0]);\n    while (lo < hi) { const std::size_t mid = lo + (hi - lo) / 2;\n        if (table[mid].number == number) return &table[mid];\n        if (table[mid].number < number) lo = mid + 1; else hi = mid;\n    }\n    return nullptr;\n}\nstd::size_t count() noexcept { return sizeof(table) / sizeof(table[0]); }\n}\n''', encoding='utf-8')
    numbers = [e['number'] for e in entries]
    print(f'Parsed {len(entries)} entries; range {min(numbers)}..{max(numbers)}; generated {args.out}')

if __name__ == '__main__':
    try: main()
    except (OSError, ValueError) as e:
        print(f'error: {e}', file=sys.stderr); sys.exit(1)
