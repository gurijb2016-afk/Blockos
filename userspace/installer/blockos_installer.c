/* BlockOS installer, X11 client.
 *
 * Raw X11 protocol client (no Xlib), same style as userspace/tests/xclient.c.
 * Runs inside the X session started by /system/install-x11.sh.
 *
 * Flow: language picker -> welcome -> target disk -> confirm -> install -> reboot.
 *   Keys: Up/Down move, Enter selects, Esc goes back (cancels on the picker).
 *   Mouse: click a row or button (the keyboard does not reach X clients yet, see README).
 *
 * The disk work is in disk_install.c: GPT + FAT32 on the target, BOOTX64.EFI copied from the
 * disk this installer booted from.
 *
 * Glyphs: installer_glyphs.h (generated by scripts/installer/gen_install_font.py
 * from LiberationSans + Noto Sans CJK). Strings: installer_strings.h (from
 * scripts/installer/strings.py).
 */
