/* X11 keycodes (xkb evdev layout: keycode = Linux KEY_* + 8) */
#define XK_ESC 9
#define XK_RETURN 36
#define XK_KP_ENTER 104
#define XK_UP 111
#define XK_DOWN 116

#define COL_BG 0x0B1420u
#define COL_FG 0xE8EEF5u
#define COL_DIM 0x8A9BB0u
#define COL_SEL_BG 0x2F6FD6u
#define COL_SEL_FG 0xFFFFFFu

/* Log lines go to stdout (flushed) and to a small buffer that the window shows at the bottom,
 * because the X session hides the console. */
static char log_lines[10][96];
static int show_log;                 /* set on failure: the log is drawn then */
static unsigned log_count;
static void log_line(const char *fmt, ...) {
    char tmp[96];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(tmp, sizeof tmp, fmt, ap);
    va_end(ap);
    printf("%s\n", tmp);
    fflush(stdout);
    strncpy(log_lines[log_count % 10], tmp, sizeof tmp - 1);
    log_count++;
}
#define LOG(...) log_line(__VA_ARGS__)

static int fd = -1;
static uint32_t win_w = 960, win_h = 640;
static uint32_t *canvas;
static uint32_t gc_id;
static uint32_t win_id;
static uint32_t max_req_bytes = 262144;

static void fill_canvas_bg(void);
static void get_all(void *buf, size_t n);
static void draw_log(void);
static void present(void);

/* Fatal error: if the window exists, keep it open with the log so the reason stays visible. */
static void die(const char *what) {
    LOG("FAILED: %s", what);
    if (!win_id || !canvas) exit(1);
    show_log = 1;
    fill_canvas_bg();
    draw_log();
    present();
    for (;;) {
        unsigned char ev[32];
        get_all(ev, sizeof ev);
        if ((ev[0] & 0x7f) == 2) exit(1);   /* any key closes */
    }
}

static void wait_a_little(void) {
    struct timespec ts = {0, 1000000};
    nanosleep(&ts, 0);
}

static void put_all(const void *buf, size_t n) {
    const unsigned char *p = buf;
    while (n) {
        ssize_t w = write(fd, p, n);
        if (w < 0 && errno == EAGAIN) { wait_a_little(); continue; }
        if (w <= 0) die("write");
        p += w;
        n -= (size_t)w;
    }
}

static void get_all(void *buf, size_t n) {
    unsigned char *p = buf;
    while (n) {
        ssize_t r = read(fd, p, n);
        if (r < 0 && errno == EAGAIN) { wait_a_little(); continue; }
        if (r <= 0) die("read");
        p += r;
        n -= (size_t)r;
    }
}

static void put16(unsigned char *b, int off, uint16_t v) { b[off] = v & 0xff; b[off + 1] = v >> 8; }
static void put32(unsigned char *b, int off, uint32_t v) {
    b[off] = v & 0xff; b[off + 1] = (v >> 8) & 0xff; b[off + 2] = (v >> 16) & 0xff; b[off + 3] = v >> 24;
}
static uint32_t get32(const unsigned char *b, int off) {
    return (uint32_t)b[off] | ((uint32_t)b[off + 1] << 8) | ((uint32_t)b[off + 2] << 16) | ((uint32_t)b[off + 3] << 24);
}
static uint16_t get16(const unsigned char *b, int off) { return (uint16_t)(b[off] | (b[off + 1] << 8)); }

/* ---------- drawing into the client-side canvas (0x00RRGGBB) ---------- */

/* Glyph pixels are thresholded: the canvas then holds only palette colours, which the
 * window can draw exactly with PolyFillRectangle (the same request xclient uses). */
static void blend_px(int x, int y, uint32_t color, uint8_t a) {
    if (x < 0 || y < 0 || (uint32_t)x >= win_w || (uint32_t)y >= win_h || a < 128) return;
    canvas[(uint32_t)y * win_w + (uint32_t)x] = color;
}

static void fill_canvas(uint32_t color) {
    for (uint32_t i = 0; i < win_w * win_h; ++i) canvas[i] = color;
}

static void fill_rect(int x, int y, int w, int h, uint32_t color) {
    for (int yy = y; yy < y + h; ++yy)
        for (int xx = x; xx < x + w; ++xx)
            blend_px(xx, yy, color, 255);
}

static const struct InstallerGlyph *find_glyph(uint32_t cp) {
    size_t lo = 0, hi = installer_glyph_count;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (installer_glyph_table[mid].cp < cp) lo = mid + 1;
        else hi = mid;
    }
    if (lo < installer_glyph_count && installer_glyph_table[lo].cp == cp) return &installer_glyph_table[lo];
    return 0;
}

/* Minimal UTF-8 decoder; unknown codepoints advance by a space. */
static uint32_t next_cp(const char **s) {
    const uint8_t c = (uint8_t)*(*s)++;
    if (c < 0x80) return c;
    int extra = (c >= 0xF0) ? 3 : (c >= 0xE0) ? 2 : (c >= 0xC0) ? 1 : 0;
    uint32_t cp = (extra == 3) ? (c & 0x07u) : (extra == 2) ? (c & 0x0Fu) : (extra == 1) ? (c & 0x1Fu) : 0x3Fu;
    for (int i = 0; i < extra && (uint8_t)**s >= 0x80 && (uint8_t)**s < 0xC0; ++i)
        cp = (cp << 6) | ((uint8_t)*(*s)++ & 0x3Fu);
    return cp;
}

static uint32_t text_width(const char *s) {
    uint32_t w = 0;
    while (*s) {
        const struct InstallerGlyph *g = find_glyph(next_cp(&s));
        w += g ? g->width : 8u;
    }
    return w;
}

static void draw_text(int x, int y, const char *s, uint32_t color) {
    while (*s) {
        const struct InstallerGlyph *g = find_glyph(next_cp(&s));
        if (!g) { x += 8; continue; }
        const uint8_t *alpha = installer_glyph_alpha + g->offset;
        for (int row = 0; row < INSTALLER_GLYPH_HEIGHT; ++row)
            for (int col = 0; col < g->width; ++col)
                blend_px(x + col, y + row, color, alpha[row * g->width + col]);
        x += g->width;
    }
}

static void draw_text_centered(int cx, int y, const char *s, uint32_t color) {
    draw_text(cx - (int)(text_width(s) / 2), y, s, color);
}

/* ---------- X11 requests ---------- */

/* Sends the canvas to the window in row bands that fit the server's max request size. */
static const uint32_t palette[] = {COL_BG, COL_FG, COL_DIM, COL_SEL_BG, COL_SEL_FG};

/* Sends the rectangles collected in buf (rect data starts at byte 12) as one PolyFillRectangle. */
static void flush_rects(unsigned char *buf, uint32_t *n) {
    if (*n == 0) return;
    memset(buf, 0, 12);
    buf[0] = 70;                              /* PolyFillRectangle */
    put16(buf, 2, (uint16_t)(3u + 2u * *n));
    put32(buf, 4, win_id);
    put32(buf, 8, gc_id);
    put_all(buf, 12u + 8u * *n);
    *n = 0;
}

static void add_rect(unsigned char *buf, uint32_t *n, uint32_t cap, uint32_t x, uint32_t y, uint32_t w, uint32_t h) {
    if (*n == cap) flush_rects(buf, n);
    unsigned char *r = buf + 12u + 8u * *n;
    put16(r, 0, (uint16_t)x);
    put16(r, 2, (uint16_t)y);
    put16(r, 4, (uint16_t)w);
    put16(r, 6, (uint16_t)h);
    ++*n;
}

/* Sends the canvas: per palette colour, one ChangeGC and the horizontal runs of that colour. */
static void present(void) {
    unsigned char *buf = malloc(max_req_bytes);
    if (!buf) die("malloc (present)");
    const uint32_t cap = (max_req_bytes - 12u) / 8u;
    for (unsigned p = 0; p < sizeof palette / sizeof palette[0]; ++p) {
        const uint32_t color = palette[p];
        unsigned char g[16];
        memset(g, 0, sizeof g);
        g[0] = 56;                            /* ChangeGC */
        put16(g, 2, 4);
        put32(g, 4, gc_id);
        put32(g, 8, 0x4);                     /* GCForeground */
        put32(g, 12, color);
        put_all(g, sizeof g);

        uint32_t n = 0;
        for (uint32_t y = 0; y < win_h; ++y) {
            uint32_t x = 0;
            while (x < win_w) {
                if (canvas[y * win_w + x] != color) { ++x; continue; }
                const uint32_t start = x;
                while (x < win_w && canvas[y * win_w + x] == color) ++x;
                add_rect(buf, &n, cap, start, y, x - start, 1);
            }
        }
        flush_rects(buf, &n);
    }
    free(buf);
}

/* ---------- screens ---------- */

static int g_sel = 0;        /* highlighted language (picker, welcome) */
static int g_lang = 0;       /* language chosen on the picker: every later screen uses it */
static int g_disk_sel = 0;   /* highlighted disk row */

enum Stage { ST_PICK, ST_WELCOME, ST_DISK, ST_CONFIRM, ST_INSTALL, ST_FAIL, ST_DONE };
static enum Stage stage = ST_PICK;
static int prog_step, prog_pct;   /* last progress shown on ST_INSTALL */

static struct DiskInfo disks[2];
static int ndisks;
static struct DiskInfo target_info;
static int install_rc;

#define M(k) installer_msgs[g_lang][MSG_##k]

/* Shows the last log lines in the bottom-left corner (debug aid, also useful on real hardware). */
static void fill_canvas_bg(void) {
    for (uint32_t i = 0; i < win_w * win_h; ++i) canvas[i] = COL_BG;
}

static void draw_log(void) {
    if (!show_log) return;
    unsigned n = log_count < 10 ? log_count : 10;
    unsigned first = log_count - n;
    for (unsigned i = 0; i < n; ++i)
        draw_text(16, (int)win_h - 16 - (int)(10 - i) * 22, log_lines[(first + i) % 10], COL_DIM);
}

/* Row geometry for every list: row i is drawn at y = list_top() + i * LIST_ROW_H. */
#define LIST_ROW_H 44
#define LIST_W 420
#define BTN_W 220
#define BTN_H 52
static int list_top(void) { return (int)win_h / 8 + 120; }

/* Row under the point (window coordinates) in a list of n rows, or -1. */
static int row_at(int x, int y, int n) {
    const int cx = (int)win_w / 2;
    if (x < cx - LIST_W / 2 || x >= cx + LIST_W / 2) return -1;
    for (int i = 0; i < n; ++i) {
        const int top = list_top() + i * LIST_ROW_H - 6;
        if (y >= top && y < top + LIST_ROW_H - 4) return i;
    }
    return -1;
}

static int in_box(int x, int y, int bx, int by, int bw, int bh) {
    return x >= bx && x < bx + bw && y >= by && y < by + bh;
}

static int btn_y(void) { return (int)win_h / 2 - 30; }
static int btn_install_x(void) { return (int)win_w / 2 - BTN_W - 10; }
static int btn_back_x(void) { return (int)win_w / 2 + 10; }
static int btn_single_x(void) { return (int)win_w / 2 - BTN_W / 2; }

static void draw_button(int x, int y, const char *label, uint32_t bg, uint32_t fg) {
    fill_rect(x, y, BTN_W, BTN_H, bg);
    draw_text_centered(x + BTN_W / 2, y + (BTN_H - INSTALLER_GLYPH_HEIGHT) / 2, label, fg);
}

static void draw_picker(void) {
    const int cx = (int)win_w / 2;
    const uint32_t n = installer_lang_count;
    const struct InstallerLang *L = &installer_langs[g_sel];
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 8, L->title, COL_FG);
    draw_text_centered(cx, (int)win_h / 8 + 44, L->pick, COL_DIM);

    for (uint32_t i = 0; i < n; ++i) {
        const int y = list_top() + (int)i * LIST_ROW_H;
        const int on = ((int)i == g_sel);
        if (on) fill_rect(cx - LIST_W / 2, y - 6, LIST_W, LIST_ROW_H - 4, COL_SEL_BG);
        draw_text_centered(cx, y, installer_langs[i].native, on ? COL_SEL_FG : COL_FG);
    }
    draw_text_centered(cx, (int)win_h - 60, L->hint, COL_DIM);
    draw_log();
    present();
}

static void draw_welcome(void) {
    const int cx = (int)win_w / 2;
    const struct InstallerLang *L = &installer_langs[g_sel];
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 3, L->native, COL_FG);
    draw_text_centered(cx, (int)win_h / 3 + 56, L->welcome, COL_FG);
    draw_text_centered(cx, (int)win_h - 60, L->hint, COL_DIM);
    draw_log();
    present();
}

static void disk_label(char *buf, size_t n, const struct DiskInfo *d) {
    snprintf(buf, n, "%s %d - %u MB", M(DISK_WORD), d->index, (unsigned)(d->sectors / 2048));
}

static void draw_disk(void) {
    const int cx = (int)win_w / 2;
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 8, M(DISK_TITLE), COL_FG);
    if (ndisks == 0) draw_text_centered(cx, list_top(), M(DISK_NONE), COL_DIM);
    for (int i = 0; i < ndisks; ++i) {
        const int y = list_top() + i * LIST_ROW_H;
        const int on = (i == g_disk_sel);
        char label[64];
        if (on) fill_rect(cx - LIST_W / 2, y - 6, LIST_W, LIST_ROW_H - 4, COL_SEL_BG);
        disk_label(label, sizeof label, &disks[i]);
        draw_text_centered(cx, y, label, on ? COL_SEL_FG : COL_FG);
    }
    draw_text_centered(cx, (int)win_h - 60, M(DISK_HINT), COL_DIM);
    draw_log();
    present();
}

static void draw_confirm(void) {
    const int cx = (int)win_w / 2;
    char label[64];
    disk_label(label, sizeof label, &target_info);
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 3 - 60, M(CONFIRM_TITLE), COL_FG);
    draw_text_centered(cx, (int)win_h / 3, label, COL_FG);
    draw_text_centered(cx, (int)win_h / 3 + 40, M(CONFIRM_TEXT), COL_DIM);
    draw_button(btn_install_x(), btn_y(), M(BTN_INSTALL), COL_SEL_BG, COL_SEL_FG);
    draw_button(btn_back_x(), btn_y(), M(BTN_BACK), COL_DIM, COL_BG);
    draw_log();
    present();
}

static void draw_progress(int step, int pct) {
    const int cx = (int)win_w / 2;
    prog_step = step;
    prog_pct = pct;
    /* overall: four steps of 25 % each */
    int overall = step * 25 + pct / 4;
    if (overall > 100) overall = 100;
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 3 - 60, M(INSTALL_TITLE), COL_FG);
    draw_text_centered(cx, (int)win_h / 3, installer_msgs[g_lang][MSG_STEP_GPT + step], COL_FG);
    const int bx = cx - 300, by = (int)win_h / 2, bw = 600, bh = 18;
    fill_rect(bx, by, bw, bh, COL_DIM);
    fill_rect(bx, by, bw * overall / 100, bh, COL_SEL_BG);
    draw_log();
    present();
}

static void draw_done(void) {
    const int cx = (int)win_w / 2;
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 3, M(DONE_TITLE), COL_FG);
    draw_text_centered(cx, (int)win_h / 3 + 48, M(DONE_TEXT), COL_DIM);
    draw_button(btn_single_x(), btn_y(), M(BTN_REBOOT), COL_SEL_BG, COL_SEL_FG);
    draw_log();
    present();
}

static void draw_fail(void) {
    const int cx = (int)win_w / 2;
    show_log = 1;
    fill_canvas(COL_BG);
    draw_text_centered(cx, (int)win_h / 3 - 60, M(ERR_FAILED), COL_FG);
    draw_text_centered(cx, (int)win_h / 3, install_rc == -10 ? M(ERR_NOSRC) : M(ERR_FAILED), COL_DIM);
    draw_button(btn_single_x(), btn_y(), M(BTN_BACK), COL_DIM, COL_BG);
    draw_log();
    present();
}

static void draw_current(void) {
    switch (stage) {
    case ST_PICK:    draw_picker(); break;
    case ST_WELCOME: draw_welcome(); break;
    case ST_DISK:    draw_disk(); break;
    case ST_CONFIRM: draw_confirm(); break;
    case ST_INSTALL: draw_progress(prog_step, prog_pct); break;
    case ST_FAIL:    draw_fail(); break;
    case ST_DONE:    draw_done(); break;
    }
}

static void save_choice(void) {
    FILE *f = fopen("/tmp/blockos-installer.lang", "w");
    if (f) { fprintf(f, "%s\n", installer_langs[g_lang].code); fclose(f); }
    LOG("language %s (%s)", installer_langs[g_lang].code, installer_langs[g_lang].native);
}

/* Welcome -> disk stage: find the source (the disk this installer booted from), list targets. */
static void enter_disk_stage(void) {
    g_lang = g_sel;
    save_choice();
    const int src = disk_find_source();
    if (src < 0) {
        LOG("BOOTX64.EFI not found on any disk");
        install_rc = -10;
        stage = ST_FAIL;
        return;
    }
    LOG("source disk %d", src);
    ndisks = disk_candidates(disks, 2);
    LOG("target disks: %d", ndisks);
    g_disk_sel = 0;
    stage = ST_DISK;
}

static void progress_cb(int step, int pct) { draw_progress(step, pct); }

static void run_install(void) {
    LOG("installing to disk %d", target_info.index);
    stage = ST_INSTALL;
    draw_progress(0, 0);
    install_rc = disk_install(target_info.index, progress_cb);
    if (install_rc == 0) {
        LOG("installation complete");
        stage = ST_DONE;
    } else {
        LOG("install failed: %d", install_rc);
        stage = ST_FAIL;
    }
}

/* ---------- connection ---------- */

static void connect_x(void) {
    fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (fd < 0) die("socket");
    struct sockaddr_un sa;
    memset(&sa, 0, sizeof sa);
    sa.sun_family = AF_UNIX;
    strcpy(sa.sun_path, "/tmp/.X11-unix/X0");
    if (connect(fd, (struct sockaddr *)&sa, sizeof sa) < 0) die("connect to X0 (start the X session first)");
}

/* Developer mode, no X session: blockos-installer --disk-install <disk index>
 * Runs the disk stage on the console with the same code as the window (for tests and for
 * installing from a shell). */
static void cli_progress(int step, int pct) {
    if (pct == 0 || pct == 100) { printf("step %d %d%%\n", step, pct); fflush(stdout); }
}

static int disk_cli(int target) {
    const int src = disk_find_source();
    printf("source disk: %d\n", src);
    fflush(stdout);
    if (src < 0) { printf("BOOTX64.EFI not found on any disk\n"); return 10; }
    printf("installing to disk %d\n", target);
    fflush(stdout);
    const int rc = disk_install(target, cli_progress);
    printf("disk_install result: %d\n", rc);
    fflush(stdout);
    return rc ? 1 : 0;
}

int main(int argc, char **argv) {
    if (argc == 3 && strcmp(argv[1], "--disk-install") == 0) return disk_cli(atoi(argv[2]));
    if (argc == 2 && strcmp(argv[1], "--reboot") == 0) machine_reboot();
    /* --preview disk|confirm|progress|done|fail: opens the window on that screen (for checks) */
    const char *preview = (argc == 3 && strcmp(argv[1], "--preview") == 0) ? argv[2] : 0;
    LOG("start");
    connect_x();
    LOG("connected");

    unsigned char req[12];
    memset(req, 0, sizeof req);
    req[0] = 'l';
    put16(req, 2, 11);
    put_all(req, sizeof req);

    unsigned char hdr[8];
    get_all(hdr, sizeof hdr);
    if (hdr[0] != 1) { LOG("X setup refused, code %d", hdr[0]); for (;;) wait_a_little(); }
    uint32_t words = get16(hdr, 6);
    unsigned char *body = malloc(words * 4u);
    if (!body) die("malloc");
    get_all(body, words * 4u);

    uint32_t rid_base = get32(body, 4);
    max_req_bytes = (uint32_t)get16(body, 18) * 4u;
    LOG("setup: %u words, image byte order %u, max request %u", (unsigned)words, body[22], max_req_bytes);
    const int bad_order = (body[22] != 0);
    uint16_t vendor_len = get16(body, 16);
    uint8_t nformats = body[21];
    int screen = 32 + ((vendor_len + 3) & ~3) + 8 * nformats;

    uint32_t root = get32(body, screen);
    uint16_t root_w = get16(body, screen + 20), root_h = get16(body, screen + 22);
    uint32_t root_visual = get32(body, screen + 32);
    uint8_t root_depth = body[screen + 38];
    LOG("X %ux%u depth %u, max request %u bytes", root_w, root_h, root_depth, max_req_bytes);
    LOG("root: %ux%u depth %u visual 0x%x", root_w, root_h, root_depth, root_visual);
    /* 24-bit or 32-bit TrueColor: colours are 0x00RRGGBB in both. */
    const int bad_depth = (root_depth != 24 && root_depth != 32);

    /* Fit the window on screen. */
    if (win_w > root_w) win_w = root_w;
    if (win_h > root_h) win_h = root_h;
    canvas = malloc((size_t)win_w * win_h * 4u);
    if (!canvas) die("canvas malloc");

    win_id = rid_base | 1;
    gc_id = rid_base | 2;

    /* CreateWindow: background + ExposureMask | KeyPressMask */
    unsigned char r[40];
    memset(r, 0, sizeof r);
    r[0] = 1;
    put16(r, 2, 10);
    put32(r, 4, win_id);
    put32(r, 8, root);
    put16(r, 12, 60);
    put16(r, 14, 40);
    put16(r, 16, (uint16_t)win_w);
    put16(r, 18, (uint16_t)win_h);
    put16(r, 22, 1);                       /* InputOutput */
    put32(r, 24, root_visual);
    put32(r, 28, 0x0802);                  /* CWBackPixel | CWEventMask */
    put32(r, 32, COL_BG);
    put32(r, 36, 0x8045);                  /* Exposure | KeyPress | ButtonPress | PointerMotion */
    put_all(r, sizeof r);

    unsigned char m[8] = {0};
    m[0] = 8;                              /* MapWindow */
    put16(m, 2, 2);
    put32(m, 4, win_id);
    put_all(m, sizeof m);

    unsigned char g[16];
    memset(g, 0, sizeof g);
    g[0] = 55;                             /* CreateGC */
    put16(g, 2, 4);
    put32(g, 4, gc_id);
    put32(g, 8, win_id);
    put32(g, 12, 0);                       /* no values */
    put_all(g, 16);

    LOG("window %u created and mapped", (unsigned)win_id);
    if (bad_order) die("unsupported image byte order");
    if (bad_depth) die("unsupported root depth (need 24 or 32)");
    draw_picker();
    LOG("picker drawn");
    if (preview) {
        g_lang = 1;                          /* English */
        ndisks = disk_candidates(disks, 2);
        target_info = disks[0];
        install_rc = -22;
        if (!strcmp(preview, "disk")) stage = ST_DISK;
        else if (!strcmp(preview, "confirm")) stage = ST_CONFIRM;
        else if (!strcmp(preview, "progress")) { stage = ST_INSTALL; prog_step = 2; prog_pct = 40; }
        else if (!strcmp(preview, "done")) stage = ST_DONE;
        else if (!strcmp(preview, "fail")) stage = ST_FAIL;
        draw_current();
        LOG("preview %s", preview);
    }
    {   /* SetInputFocus: the key presses go to this window */
        unsigned char f[12];
        memset(f, 0, sizeof f);
        f[0] = 42;
        f[1] = 1;                           /* RevertToPointerRoot */
        put16(f, 2, 3);
        put32(f, 4, win_id);
        put32(f, 8, 0);                     /* CurrentTime */
        put_all(f, sizeof f);
    }

    /* Event loop. */
    for (;;) {
        unsigned char ev[32];
        get_all(ev, sizeof ev);
        const int type = ev[0] & 0x7f;
        if (type == 0) {                     /* X error: show it in the window */
            LOG("X error code %u opcode %u seq %u", ev[1], ev[10], get16(ev, 2));
            show_log = 1;
            draw_current();
            continue;
        }
        if (type == 12) {                    /* Expose */
            draw_current();
            continue;
        }
        const int ex = (int)get16(ev, 24), ey = (int)get16(ev, 26);   /* event-x, event-y */

        if (type == 6) {                     /* MotionNotify: hover highlights a row */
            if (stage == ST_PICK) {
                const int row = row_at(ex, ey, (int)installer_lang_count);
                if (row >= 0 && row != g_sel) { g_sel = row; draw_picker(); }
            } else if (stage == ST_DISK) {
                const int row = row_at(ex, ey, ndisks);
                if (row >= 0 && row != g_disk_sel) { g_disk_sel = row; draw_disk(); }
            }
            continue;
        }

        const int click = (type == 4 && ev[1] == 1);   /* ButtonPress, left button */
        const int key = (type == 2);                   /* KeyPress */
        if (!click && !key) continue;
        const uint8_t kc = ev[1];
        const int enter = key && (kc == XK_RETURN || kc == XK_KP_ENTER);
        const int esc = key && kc == XK_ESC;

        switch (stage) {
        case ST_PICK:
            if (click) {
                const int row = row_at(ex, ey, (int)installer_lang_count);
                if (row >= 0) { g_sel = row; stage = ST_WELCOME; draw_welcome(); }
            } else if (kc == XK_UP) {
                g_sel = (g_sel + (int)installer_lang_count - 1) % (int)installer_lang_count;
                draw_picker();
            } else if (kc == XK_DOWN) {
                g_sel = (g_sel + 1) % (int)installer_lang_count;
                draw_picker();
            } else if (enter) {
                stage = ST_WELCOME;
                draw_welcome();
            } else if (esc) {
                LOG("cancelled");
                return 1;
            }
            break;

        case ST_WELCOME:
            if (esc) { LOG("cancelled"); return 1; }
            enter_disk_stage();
            draw_current();
            break;

        case ST_DISK:
            if (click) {
                const int row = row_at(ex, ey, ndisks);
                if (row >= 0) { g_disk_sel = row; target_info = disks[row]; stage = ST_CONFIRM; draw_confirm(); }
            } else if (kc == XK_UP && ndisks) {
                g_disk_sel = (g_disk_sel + ndisks - 1) % ndisks;
                draw_disk();
            } else if (kc == XK_DOWN && ndisks) {
                g_disk_sel = (g_disk_sel + 1) % ndisks;
                draw_disk();
            } else if (enter && ndisks) {
                target_info = disks[g_disk_sel];
                stage = ST_CONFIRM;
                draw_confirm();
            } else if (esc) {
                stage = ST_WELCOME;
                draw_welcome();
            }
            break;

        case ST_CONFIRM:
            if (click) {
                if (in_box(ex, ey, btn_install_x(), btn_y(), BTN_W, BTN_H)) { run_install(); draw_current(); }
                else if (in_box(ex, ey, btn_back_x(), btn_y(), BTN_W, BTN_H)) { stage = ST_DISK; draw_disk(); }
            } else if (enter) {
                run_install();
                draw_current();
            } else if (esc) {
                stage = ST_DISK;
                draw_disk();
            }
            break;

        case ST_FAIL:
            if (click ? in_box(ex, ey, btn_single_x(), btn_y(), BTN_W, BTN_H) : (enter || esc)) {
                stage = ST_WELCOME;
                draw_welcome();
            }
            break;

        case ST_INSTALL:
            break;                           /* no input while the disk is written */

        case ST_DONE:
            if (click ? in_box(ex, ey, btn_single_x(), btn_y(), BTN_W, BTN_H) : enter) {
                LOG("restarting");
                machine_reboot();
            }
            break;
        }
    }
}
